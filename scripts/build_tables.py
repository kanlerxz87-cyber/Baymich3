#!/usr/bin/env python3
"""Generate restaurants.html and hotels.html from the verified CSV sources.

Usage:  python3 scripts/build_tables.py        (run from repo root)

Rules enforced here (mirrors data/SCOPE.md):
- A blank value is shown as "Unverified", never filled in.
- Price for 2 is shown only when price_2adults_usd is present in the CSV.
- Michelin price level ($ .. $$$$) is shown as Michelin's own level, not a dollar amount.
- Every row links to its Michelin source page and its official site.
"""
import csv
import html
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAV = [
    ("index.html", "Home"), ("restaurants.html", "Starred"), ("listed.html", "Bib &amp; Listed"),
    ("hotels.html", "Hotels"), ("map.html", "Map &amp; Clusters"), ("executive-summary.html", "Summary"),
    ("questions.html", "Questions"), ("suggestions.html", "Suggestions"), ("flagged.html", "Flagged"),
    ("methodology.html", "Method"),
]


def esc(s):
    return html.escape(s or "", quote=True)


def page(title, active, body):
    cur = ' aria-current="page"'
    nav = "".join('<a href="%s"%s>%s</a>' % (href, cur if href == active else "", label)
                  for href, label in NAV)
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(title)} — SF Bay Area Michelin 2026</title>
<link rel="stylesheet" href="assets/style.css"></head>
<body><header class="top"><div class="wrap"><div class="brand">SF Bay Area Michelin<small>Guide California 2026 · Verified · Mobile-friendly</small></div>
<nav class="main">{nav}</nav></div></header>
<main>{body}</main>
<footer>Generated by scripts/build_tables.py from data/*.csv on 24 Nov 2026. Blank = Unverified (never guessed).
Sources: <a href="https://guide.michelin.com/us/en/article/michelin-guide-ceremony/guide-michelin-california">MICHELIN Guide California 2026 article</a> ·
<a href="data/restaurants.csv">restaurants.csv</a> · <a href="data/hotels.csv">hotels.csv</a> · <a href="data/verification-log-2026-11-24.md">verification log</a> · <a href="flagged.html">Flagged</a></footer>
<script src="assets/app.js"></script></body></html>
"""


def badge(status):
    s = (status or "").lower()
    if "conflict" in s:
        return '<span class="badge bad">Conflict</span>'
    if s.startswith("verified"):
        return '<span class="badge ok">Verified</span>'
    if s.startswith("partial"):
        return '<span class="badge warn">Partial</span>'
    return '<span class="badge warn">Unverified</span>'


def link(url, label):
    return f'<a href="{esc(url)}" rel="noopener">{esc(label)}</a>' if url else ""


def unv(text="Unverified"):
    return f'<span class="unv">{esc(text)}</span>'


def build_restaurants():
    rows = list(csv.DictReader(open(os.path.join(ROOT, "data/restaurants.csv"), encoding="utf-8")))
    core = [r for r in rows if r["scope"] == "Core"]
    ext = [r for r in rows if r["scope"] != "Core"]
    stars3 = sum(r["distinction"] == "3 Stars" for r in core)
    stars2 = sum(r["distinction"] == "2 Stars" for r in core)
    stars1 = sum(r["distinction"] == "1 Star" for r in core)
    out = []
    for r in rows:
        dist = r["distinction"]
        status = f'<span class="badge star">{esc(dist)}</span>'
        if r.get("green_star") == "Yes":
            status += ' <span class="badge ok">Green Star</span>'
        status += f'<br><span class="small">{esc(r["scope"])} · {esc(r["cluster"])}</span>'
        # price for 2 (total)
        if r.get("price_2adults_usd"):
            basis = esc(r.get("price_basis", ""))
            price = (f'<b>${esc(r["price_2adults_usd"])}</b> total<br><span class="small">{basis}</span>'
                     f'<br><span class="small">Source: {link(r.get("price_source", ""), "official page")}</span>')
        else:
            price = unv("Price for 2: Unverified")
        if r.get("michelin_price_level"):
            price += f'<br><span class="small">Michelin level {esc(r["michelin_price_level"])} (not a dollar amount)</span>'
        # hours
        hrs = []
        if r.get("days_open"):
            hrs.append(f'<b>{esc(r["days_open"])}</b>')
        if r.get("hours"):
            hrs.append(esc(r["hours"]))
        if r.get("michelin_hours_2026"):
            hrs.append(f'<span class="small">Michelin: {esc(r["michelin_hours_2026"])}</span>')
        hours_html = "<br>".join(hrs) if hrs else unv("Hours: Unverified")
        if r.get("exceptions"):
            hours_html += f'<br><span class="small">Exceptions: {esc(r["exceptions"])}</span>'
        # social
        soc = []
        for key, label in (("instagram", "Instagram"), ("youtube", "YouTube"), ("tiktok", "TikTok")):
            if r.get(key):
                soc.append(link(r[key], label))
        social = "<br>".join(soc) if soc else unv("None verified")
        # links
        lk = [link(r.get("michelin_url", ""), "Michelin page"), link(r.get("official_url", ""), "Official site")]
        links = "<br>".join(x for x in lk if x) or unv("No link")
        notes = esc(r.get("notes", ""))
        verification = (f'{badge(r.get("verification_status"))}<br><span class="small">{esc(r.get("verification_status", ""))}</span>'
                        f'<br><span class="small">{notes}</span>')
        out.append(
            f'<tr data-group="{esc(dist)} {esc(r["cluster"])}">'
            f'<td data-label="Restaurant"><b>{esc(r["name"])}</b><br><span class="small">{esc(r["city"])}</span></td>'
            f'<td data-label="Michelin status">{status}</td>'
            f'<td data-label="Cuisine &amp; address">{esc(r.get("cuisine", ""))}<br><span class="small">{esc(r.get("address", "")) or unv("Address: Unverified")}</span></td>'
            f'<td data-label="Price for 2 adults">{price}</td>'
            f'<td data-label="Days &amp; hours">{hours_html}</td>'
            f'<td data-label="Social">{social}</td>'
            f'<td data-label="Links">{links}</td>'
            f'<td data-label="Verification">{verification}</td></tr>')
    body = f"""<h1>Michelin restaurants — SF Bay Area</h1>
<p>Edition: MICHELIN Guide California 2026 (revealed 24 Jun 2026). <b>{len(core)} Core</b> starred restaurants
({stars3}×3★, {stars2}×2★, {stars1}×1★) + {len(ext)} Extension (outside the 9-county Bay Area, shown for reference).
Listed-only (Bib Gourmand / Selected) restaurants are on <a href="listed.html">Bib &amp; Listed</a>.</p>
<div class="note"><b>How to read:</b> <span class="badge ok">Verified</span> = checked against the official Michelin page or restaurant site.
<span class="badge warn">Partial/Unverified</span> = at least one value could not be confirmed, so it is blank.
<span class="badge bad">Conflict</span> = two official sources disagree; both are shown and the row is on the Flagged page.
Price for 2 = per-person price × 2 + service charge (formula shown), excluding tax and beverages.</div>
<div class="controls"><input data-filter="#restTable" placeholder="Search name, city, cuisine, status…" aria-label="Search">
<select data-filter-select="#restTable" aria-label="Filter by distinction">
<option value="">All distinctions</option><option value="3 Stars">3 Stars</option><option value="2 Stars">2 Stars</option>
<option value="1 Star">1 Star</option></select></div>
<div class="tblwrap"><table id="restTable" class="stack"><thead><tr>
<th>Restaurant</th><th>Michelin status</th><th>Cuisine &amp; address</th><th>Price for 2 (total)</th>
<th>Days &amp; hours</th><th>Social</th><th>Links</th><th>Verification &amp; notes</th></tr></thead>
<tbody>{''.join(out)}</tbody></table></div>
<p class="small">Source for every row: Michelin restaurant page (hours, price level, website) and the Michelin 2026 California article (stars). Prices are not guessed: they appear only where the official page states them.</p>"""
    return page("Starred restaurants", "restaurants.html", body)


def build_hotels():
    rows = list(csv.DictReader(open(os.path.join(ROOT, "data/hotels.csv"), encoding="utf-8")))
    out = []
    for r in rows:
        site = link(r.get("official_url", ""), "Official site") or unv("No official link")
        addr = esc(r.get("address", "")) or unv("Address: Unverified")
        out.append(
            f'<tr><td data-label="Rank"><b>{esc(r["rank"])}</b></td>'
            f'<td data-label="Hotel"><b>{esc(r["hotel"])}</b><br><span class="small">{esc(r["city"])} · {esc(r["cluster"])}</span></td>'
            f'<td data-label="Starred in cluster">{esc(r["starred_in_cluster"])}</td>'
            f'<td data-label="Address">{addr}</td>'
            f'<td data-label="Why ranked">{esc(r.get("why_ranked", ""))}<br><span class="small">{esc(r.get("rank_basis", ""))}</span></td>'
            f'<td data-label="Links">{site}</td>'
            f'<td data-label="Verification">{badge(r.get("verification_status"))}<br><span class="small">{esc(r.get("verification_status", ""))}</span>'
            f'<br><span class="small">{esc(r.get("notes", ""))}</span></td></tr>')
    body = f"""<h1>Hotels ranked by Michelin density</h1>
<p>Ranking metric: number of <b>Core starred restaurants</b> in the hotel's cluster (data/restaurants.csv). Ranks 1–14 are sorted by that count.
<b>Within a cluster, hotels are tied</b> until straight-line distances are calculated from verified coordinates (not yet done).</p>
<div class="note">Prices per night are not collected (dynamic pricing; no official static price source). Michelin Keys counts are not verified.</div>
<div class="controls"><input data-filter="#hotelTable" placeholder="Search hotel, cluster, address…" aria-label="Search hotels"></div>
<div class="tblwrap"><table id="hotelTable" class="stack"><thead><tr>
<th>Rank</th><th>Hotel</th><th>Starred in cluster</th><th>Address</th><th>Why ranked</th><th>Link</th><th>Verification</th>
</tr></thead><tbody>{''.join(out)}</tbody></table></div>"""
    return page("Hotels ranked", "hotels.html", body)


# ---- minimal Markdown -> HTML for docs/*.md (headings, lists, tables, quotes, bold, code, links)
import re

DOCS = [
    ("docs/executive-summary.md", "executive-summary.html", "Executive summary", "executive-summary.html"),
    ("docs/questions.md", "questions.html", "Questions & answers", "questions.html"),
    ("docs/suggestions.md", "suggestions.html", "Suggestions (review first)", "suggestions.html"),
    ("docs/flagged.md", "flagged.html", "Flagged for review", "flagged.html"),
    ("docs/methodology.md", "methodology.html", "Method", "methodology.html"),
]


def inline(t):
    t = esc(t)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+|[^)\s]+)\)", lambda m: f'<a href="{m.group(2)}">{m.group(1)}</a>', t)
    return t


def md_to_html(text):
    out, lines, i = [], text.splitlines(), 0
    in_list = False
    def close_list():
        nonlocal in_list
        if in_list:
            out.append("</ul>"); in_list = False
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("|"):
            close_list()
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(lines[i]); i += 1
            cells = [[c.strip() for c in r.strip().strip("|").split("|")] for r in rows]
            head, body = cells[0], [c for c in cells[2:]]
            t = ['<div class="tblwrap"><table class="stack"><thead><tr>' + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead><tbody>"]
            for r in body:
                t.append("<tr>" + "".join(f'<td data-label="{esc(head[j]) if j < len(head) else ""}">{inline(c)}</td>' for j, c in enumerate(r)) + "</tr>")
            t.append("</tbody></table></div>")
            out.append("".join(t))
            continue
        if ln.startswith("- "):
            if not in_list:
                out.append("<ul>"); in_list = True
            out.append(f"<li>{inline(ln[2:])}</li>")
        else:
            close_list()
            if ln.startswith("### "): out.append(f"<h3>{inline(ln[4:])}</h3>")
            elif ln.startswith("## "): out.append(f"<h2>{inline(ln[3:])}</h2>")
            elif ln.startswith("# "): out.append(f"<h1>{inline(ln[2:])}</h1>")
            elif ln.startswith("> "): out.append(f'<div class="note">{inline(ln[2:])}</div>')
            elif ln.strip() == "": pass
            else: out.append(f"<p>{inline(ln)}</p>")
        i += 1
    close_list()
    return "\n".join(out)


def build_docs():
    for src, dst, title, active in DOCS:
        text = open(os.path.join(ROOT, src), encoding="utf-8").read()
        body = md_to_html(text)
        body += ('<p class="small">Source file: <code>' + esc(src) + '</code>. Generated by scripts/build_tables.py on 24 Nov 2026.</p>')
        with open(os.path.join(ROOT, dst), "w", encoding="utf-8") as f:
            f.write(page(title, active, body))
    print("wrote", ", ".join(d[1] for d in DOCS))


def main():
    with open(os.path.join(ROOT, "restaurants.html"), "w", encoding="utf-8") as f:
        f.write(build_restaurants())
    with open(os.path.join(ROOT, "hotels.html"), "w", encoding="utf-8") as f:
        f.write(build_hotels())
    build_docs()
    print("wrote restaurants.html, hotels.html")


if __name__ == "__main__":
    main()
