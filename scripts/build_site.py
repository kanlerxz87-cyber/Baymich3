#!/usr/bin/env python3
"""Regenerate the data-driven pages from the CSVs in data/.

Outputs: restaurants.html, hotels.html, flagged.html, executive-summary.html, questions.html, suggestions.html (from docs/*.md)
Run from repo root:  python3 scripts/build_site.py
Other pages (index, listed, map, methodology) are hand-maintained and are NOT touched.
"""
import csv
import html
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
E = html.escape


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def nav(active):
    items = [
        ("index.html", "Home"), ("restaurants.html", "Starred"),
        ("listed.html", "Bib &amp; Listed"), ("hotels.html", "Hotels"),
        ("map.html", "Map &amp; Clusters"), ("executive-summary.html", "Summary"),
        ("questions.html", "Questions"), ("suggestions.html", "Suggestions"),
        ("flagged.html", "Flagged"), ("methodology.html", "Method"),
    ]
    parts = []
    for href, label in items:
        cur = ' aria-current="page"' if href == active else ""
        parts.append(f'<a href="{href}"{cur}>{label}</a>')
    links = "".join(parts)
    return (
        '<header class="top"><div class="wrap"><div class="brand">SF Bay Area Michelin'
        '<small>Guide California 2026 · Verified · Mobile-friendly</small></div>'
        f'<nav class="main">{links}</nav></div></header>'
    )


def page(title, active, heading, intro, body):
    return (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>{E(title)} — SF Bay Area Michelin 2026</title>"
        '<link rel="stylesheet" href="assets/style.css"></head><body>'
        f"{nav(active)}<main><h1>{heading}</h1><p>{intro}</p>{body}</main>"
        '<footer>Sources: MICHELIN Guide California 2026 (guide.michelin.com) and restaurant/hotel '
        'official websites. Blank or "Unverified" = not confirmed from an official source; '
        'never inferred. Generated by scripts/build_site.py from data/*.csv.</footer>'
        '<script src="assets/app.js"></script></body></html>\n'
    )


def status_badge(status):
    s = (status or "").strip()
    low = s.lower()
    if not s:
        return '<span class="badge warn">Unverified</span>'
    if low.startswith("verified") and "unverified" not in low and "not on" not in low:
        return '<span class="badge ok">Verified</span>'
    if low.startswith("verified") or low.startswith("partial"):
        return '<span class="badge warn">Partial</span>'
    return '<span class="badge warn">Unverified</span>'


def link(url, label):
    return f'<a href="{E(url)}" rel="noopener">{E(label)}</a>' if url else ""


def build_restaurants():
    rows = read("data/restaurants.csv")
    core = [r for r in rows if r["scope"] == "Core"]
    ext = [r for r in rows if r["scope"] != "Core"]
    count = {d: sum(1 for r in core if r["distinction"] == d) for d in ("3 Stars", "2 Stars", "1 Star")}
    trs = []
    for r in rows:
        group = f'{r["distinction"]} {r["scope"]}'
        star = f'<span class="badge star">{E(r["distinction"])}</span>'
        scope_tag = '' if r["scope"] == "Core" else ' <span class="badge warn">Extension</span>'
        name = f'<b>{E(r["name"])}</b>' if r["name"] else "<i>Unnamed</i>"
        if r["michelin_url"]:
            name = f'<a href="{E(r["michelin_url"])}">{name}</a>'
        if r["price_2adults_usd"]:
            price = (f'<b>${E(r["price_2adults_usd"])}</b> total'
                     f'<br><span class="small">{E(r["price_basis"])}</span>')
        else:
            price = '<span class="warn">Unverified — not shown</span>'
        if r["michelin_price_tier"]:
            price += f'<br><span class="small">Michelin tier {E(r["michelin_price_tier"])} (not a $ amount)</span>'
        hours_bits = [b for b in (r["days_open"], r["hours"], r["exceptions"]) if b]
        hours = "<br>".join(E(b) for b in hours_bits) if hours_bits else '<span class="warn">Unverified</span>'
        socials = [link(r[k], lbl) for k, lbl in (("instagram", "Instagram"), ("youtube", "YouTube"), ("tiktok", "TikTok")) if r.get(k)]
        social = "<br>".join(socials) if socials else '<span class="warn">No verified link yet</span>'
        sources = [link(r["michelin_url"], "Michelin page"), link(r["official_url"], "Official site")]
        sources = "<br>".join(s for s in sources if s) or '<span class="warn">No official link</span>'
        trs.append(
            f'<tr data-group="{E(group)}"><td>{name}<br><span class="small">{E(r["city"])} · {E(r["cluster"])}</span>'
            f'<br>{star}{scope_tag} {status_badge(r["verification_status"])}</td>'
            f'<td>{E(r["cuisine"])}<br><span class="small">{E(r["address"]) or "<span class=warn>Unverified</span>"}</span></td>'
            f'<td>{price}</td><td>{hours}</td><td>{social}</td>'
            f'<td>{sources}<br><span class="small">{E(r["verification_status"])}</span>'
            f'{"<br><span class=small>" + E(r["notes"]) + "</span>" if r["notes"] else ""}</td></tr>'
        )
    stats = (
        '<div class="grid">'
        f'<div class="stat"><b>{len(core)}</b><span>Core starred (9-county)</span></div>'
        f'<div class="stat"><b>{count["3 Stars"]}</b><span>3 Stars</span></div>'
        f'<div class="stat"><b>{count["2 Stars"]}</b><span>2 Stars</span></div>'
        f'<div class="stat"><b>{count["1 Star"]}</b><span>1 Star</span></div>'
        f'<div class="stat"><b>{len(ext)}</b><span>Extension (outside 9 counties)</span></div>'
        '</div>'
    )
    controls = (
        '<div class="controls"><input data-filter="#restTable" placeholder="Search name, city, cuisine…">'
        '<select data-filter-select="#restTable"><option value="">All distinctions</option>'
        '<option value="3 Stars">3 Stars</option><option value="2 Stars">2 Stars</option>'
        '<option value="1 Star">1 Star</option><option value="Extension">Extension only</option></select></div>'
    )
    table = (
        '<div class="tblwrap"><table id="restTable"><thead><tr>'
        '<th>Restaurant</th><th>Cuisine / Address</th><th>Price for 2 adults (USD)</th>'
        '<th>Days / Hours / Exceptions</th><th>Social</th><th>Sources &amp; verification</th>'
        '</tr></thead><tbody>' + "".join(trs) + '</tbody></table></div>'
    )
    intro = ('All 44 rows are MICHELIN-starred in the 2026 California guide: '
             'the 41 Core rows (9-county Bay Area) plus 3 Extension rows. '
             'Listed-only (Bib Gourmand / Recommended) restaurants are on the '
             '<a href="listed.html">Bib &amp; Listed</a> page. '
             'Prices are shown only when an official source confirms them; otherwise "Unverified".')
    return page("Starred restaurants", "restaurants.html", "Starred restaurants (2026)", intro, stats + controls + table)


def build_hotels():
    rows = read("data/hotels.csv")
    trs = []
    for r in rows:
        site = link(r["official_url"], "Official site") or '<span class="warn">Not yet verified</span>'
        mich = link(r["michelin_hotel_source"], "Michelin hotels")
        trs.append(
            f'<tr><td><b>{E(r["rank"])}</b></td>'
            f'<td><b>{E(r["hotel"])}</b><br><span class="small">{E(r["city"])} · {E(r["cluster"])}</span></td>'
            f'<td>{E(r["starred_in_cluster"])}</td>'
            f'<td>{E(r["address"])}</td>'
            f'<td>{site}<br>{mich}</td>'
            f'<td>{status_badge(r["verification_status"])}<br><span class="small">{E(r["verification_status"])}</span>'
            f'<br><span class="small">{E(r["why_ranked"])}</span>'
            f'{"<br><span class=small>" + E(r["notes"]) + "</span>" if r["notes"] else ""}</td></tr>'
        )
    intro = ('Ranked by the number of MICHELIN-starred restaurants (2026, Core) in each hotel\'s cluster. '
             'Ties are ordered editorially — this is NOT a distance count yet (see '
             '<a href="flagged.html">Flagged</a> and data/hotels.md). Nightly rates are not collected (dynamic pricing).')
    table = (
        '<div class="tblwrap"><table><thead><tr><th>Rank</th><th>Hotel</th><th>Starred in cluster</th>'
        '<th>Address (as on file)</th><th>Sources</th><th>Verification &amp; notes</th></tr></thead><tbody>'
        + "".join(trs) + '</tbody></table></div>'
    )
    return page("Hotels", "hotels.html", "Hotels ranked by Michelin density", intro, table)


