def build_flagged():
    trs = []
    for fid, item, found, action, src in FLAGS:
        s = f'<a href="{E(src)}">source</a>' if src else ''
        badge = 'ok' if action.startswith("FIXED") or action.startswith("Checked") else 'warn'
        trs.append(f'<tr><td>{fid}</td><td><b>{E(item)}</b></td><td>{E(found)}</td>'
                   f'<td><span class="badge {badge}">{E(action)}</span></td><td>{s}</td></tr>')
    intro = ("Every irregularity found in this review. <b>FIXED</b> = corrected in the data and checked against a source. "
             "<b>OPEN</b> = needs a decision or a fetch before it can be resolved. Open items do not block the site.")
    table = ('<div class="tblwrap"><table><thead><tr><th>ID</th><th>Item</th><th>What we found</th>'
             '<th>Status</th><th>Source</th></tr></thead><tbody>' + "".join(trs) + '</tbody></table></div>')
    return page("Flagged for review", "flagged.html", "Flagged for review", intro, table)


def inline(text):
    import re
    t = E(text)
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+|[^)\s]+)\)", r'<a href="\2">\1</a>', t)
    return t


def md_to_body(md):
    """Small Markdown subset: headings, bullets, pipe tables, paragraphs, bold, links."""
    out, title, lines = [], "", md.splitlines()
    i, in_ul = 0, False
    def close_ul():
        nonlocal in_ul
        if in_ul:
            out.append("</ul>")
            in_ul = False
    while i < len(lines):
        ln = lines[i].rstrip()
        if ln.startswith("# ") and not title:
            title = ln[2:].strip(); i += 1; continue
        if ln.startswith("|"):
            close_ul()
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(set(c) <= set("-: ") for c in cells):
                    rows.append(cells)
                i += 1
            head, body = rows[0], rows[1:]
            out.append('<div class="tblwrap"><table><thead><tr>' + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead><tbody>")
            for r in body:
                out.append("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>")
            out.append("</tbody></table></div>")
            continue
        if ln.startswith("## "):
            close_ul(); out.append(f"<h2>{inline(ln[3:])}</h2>")
        elif ln.startswith("### "):
            close_ul(); out.append(f"<h3>{inline(ln[4:])}</h3>")
        elif ln.startswith("- "):
            if not in_ul:
                out.append("<ul>"); in_ul = True
            out.append(f"<li>{inline(ln[2:])}</li>")
        elif re.match(r"^\d+\. ", ln):
            close_ul(); out.append(f"<p>{inline(ln)}</p>")
        elif ln.strip() == "":
            close_ul()
        else:
            close_ul(); out.append(f"<p>{inline(ln)}</p>")
        i += 1
    close_ul()
    return title, "\n".join(out)


def build_doc(path, active, heading_fallback):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        title, body = md_to_body(f.read())
    return page(title or heading_fallback, active, title or heading_fallback,
                f'Source: <code>{E(path)}</code> (rendered from Markdown). Verified facts link to official sources.', body)


def main():
    outputs = {
        "restaurants.html": build_restaurants(),
        "hotels.html": build_hotels(),
        "flagged.html": build_flagged(),
        "executive-summary.html": build_doc("docs/executive-summary.md", "executive-summary.html", "Executive summary"),
        "questions.html": build_doc("docs/questions.md", "questions.html", "Questions"),
        "suggestions.html": build_doc("docs/suggestions.md", "suggestions.html", "Suggestions"),
    }
    for name, content in outputs.items():
        with open(os.path.join(ROOT, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print("wrote", name, len(content), "bytes")


if __name__ == "__main__":
    main()
